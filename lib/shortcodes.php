/**
 * Creates a link to search results.
 *
 * Using this is generally not a brilliant idea, actually. Google doesn't like
 * it if you create links to internal search results.
 *
 * Usage: [search term='tomato']tomatoes[/search] would create a link like this:
 * <a href="/?s=tomato">tomatoes</a>
 *
 * Set 'phrase' to something else than 'not' to make the search term a phrase.
 *
 * @global object $wpdb The WordPress database interface.
 *
 * @param array  $atts    The shortcode attributes. If 'term' is set, will use
 * it as the search term, otherwise the content word is used as the term.
 * @param string $content The content inside the shortcode tags.
 *
 * @return string A link to search results.
 */
function relevanssi_shortcode( $atts, $content ) {
	$attributes = shortcode_atts(
		array(
			'term'   => false,
			'phrase' => 'not',
		),
		$atts
	);

	$term   = $attributes['term'];
	$phrase = $attributes['phrase'];

	if ( false !== $term ) {
		$term = rawurlencode( relevanssi_strtolower( $term ) );
	} else {
		$term = rawurlencode( wp_strip_all_tags( relevanssi_strtolower( $content ) ) );
	}

	if ( 'not' !== $phrase ) {
		$term = '%22' . $term . '%22';
	}

	$link = get_bloginfo( 'url' ) . "/?s=$term";
	$pre  = "<a rel='nofollow' href='$link'>"; // rel='nofollow' for Google.
	$post = '</a>';

	return $pre . do_shortcode( $content ) . $post;
}

/**
 * Does nothing.
 *
 * In normal use, the [noindex] shortcode does nothing.
 *
 * @param array  $atts    The shortcode attributes. Not used.
 * @param string $content The content inside the shortcode tags.
 *
 * @return string The shortcode content.
 */
function relevanssi_noindex_shortcode( $atts, $content ) {
	return do_shortcode( $content );
}

/**
 * Returns nothing.
 *
 * During indexing, the [noindex] shortcode returns nothing.
 *
 * @return string An empty string.
 */
function relevanssi_noindex_shortcode_indexing() {
	return '';
}

/**
 * Returns a search form.
 *
 * Returns a search form generated by get_search_form(). Any attributes passed to the
 * shortcode will be passed onto the search form, for example like this:
 *
 * [searchform post_types='post,product']
 *
 * This would add a
 *
 * <input type="hidden" name="post_types" value="post,product" />
 *
 * to the search form.
 * The optional modal context adds semantic wrappers and classes for modal
 * filter controls while preserving the legacy [searchform] markup.
 *
 * @param array   $atts          The shortcode attributes.
 * @param boolean $modal_context Whether the form is rendered inside a modal search form.
 *
 * @return string A search form.
 */
function relevanssi_search_form( $atts, $modal_context = false ) {
	$form = get_search_form( false );
	if ( is_array( $atts ) ) {
		$additional_fields = array();
		foreach ( $atts as $key => $value ) {
			if ( 'dropdown' === substr( $key, 0, 8 ) ) {
				$key = 'dropdown';
			}
			if ( 'checklist' === substr( $key, 0, 9 ) ) {
				$key = 'checklist';
			}
			if ( 'post_type_boxes' === $key ) {
				$post_types = explode( ',', $value );
				if ( is_array( $post_types ) ) {
					$post_type_objects = get_post_types( array(), 'objects' );
					if ( $modal_context ) {
						$additional_fields[] = '<fieldset class="post_types relevanssi-search-form__post-types">';
						$additional_fields[] = '<legend>' . esc_html__( 'Post types', 'relevanssi' ) . '</legend>';
						$additional_fields[] = '<div class="relevanssi-search-form__choices">';
					} else {
						$additional_fields[] = '<div class="post_types"><strong>Post types</strong>: ';
					}
					foreach ( $post_types as $post_type ) {
						$post_type = trim( $post_type );
						$checked   = '';
						if ( '*' === substr( $post_type, 0, 1 ) ) {
							$post_type = substr( $post_type, 1 );
							$checked   = ' checked="checked" ';
						}
						if ( isset( $post_type_objects[ $post_type ] ) ) {
							if ( $modal_context ) {
								$post_type_class = sanitize_html_class( $post_type );
								$post_type_id    = 'relevanssi-search-post-type-' . $post_type_class . '-' . wp_unique_id();
								$post_type_label = $post_type_objects[ $post_type ]->name;
								if ( isset( $post_type_objects[ $post_type ]->labels->name ) ) {
									$post_type_label = $post_type_objects[ $post_type ]->labels->name;
								}
								$additional_fields[] = sprintf(
									'<label class="post_type post_type_%1$s relevanssi-search-form__choice" for="%2$s"><input id="%2$s" type="checkbox" name="post_types[]" value="%3$s"%4$s /> %5$s</label>',
									esc_attr( $post_type_class ),
									esc_attr( $post_type_id ),
									esc_attr( $post_type ),
									$checked,
									esc_html( $post_type_label )
								);
							} else {
								$additional_fields[] = '<span class="post_type post_type_' . $post_type . '">'
								. '<input type="checkbox" name="post_types[]" value="' . $post_type . '"' . $checked . '/> '
								. $post_type_objects[ $post_type ]->name . '</span>';
							}
						}
					}
					$additional_fields[] = $modal_context ? '</div></fieldset>' : '</div>';
				}
			} elseif ( 'dropdown' === $key && 'post_type' === $value ) {
				$field = $modal_context
					? '<label class="relevanssi-search-form__field"><span class="relevanssi-search-form__field-label">' . esc_html__( 'Filter by post type', 'relevanssi' ) . '</span><select name="post_type">'
					: '<select name="post_type">';
				$types = get_option( 'relevanssi_index_post_types', array() );
				if ( ! is_array( $types ) ) {
					$types = array();
				}
				foreach ( $types as $type ) {
					if ( post_type_exists( $type ) ) {
						$object = get_post_type_object( $type );
						$field .= '<option value="' . esc_attr( $type ) . '">' . esc_html( $object->labels->singular_name ) . '</option>';
					}
				}
				$field              .= $modal_context ? '</select></label>' : '</select>';
				$additional_fields[] = $field;

			} elseif ( 'dropdown' === $key && 'post_type' !== $value ) {
				$name = $value;
				if ( 'category' === $value ) {
					$name = 'cat';
				}
				if ( 'post_tag' === $value ) {
					$name = 'tag';
				}
				$args     = array(
					'taxonomy'          => $value,
					'echo'              => 0,
					'hide_if_empty'     => true,
					'show_option_none'  => __( 'None' ),
					'name'              => $name,
					'option_none_value' => 0,
					'orderby'           => 'name',
				);
				$dropdown = wp_dropdown_categories(
					/**
					 * Filters the arguments for the Relevanssi search form
					 * taxonomy dropdowns.
					 *
					 * Filters the argument array for wp_dropdown_categories().
					 *
					 * @param array $args The arguments for the dropdown.
					 * @see wp_dropdown_categories()
					 */
					apply_filters( 'relevanssi_searchform_dropdown_args', $args )
				);
				if ( $modal_context && ! empty( $dropdown ) ) {
					$taxonomy_label  = $value;
					$taxonomy_object = get_taxonomy( $value );
					if ( $taxonomy_object && isset( $taxonomy_object->labels->name ) ) {
						$taxonomy_label = $taxonomy_object->labels->name;
					}
					/* translators: %s: taxonomy name. */
					$filter_label = sprintf( esc_html__( 'Filter by %s', 'relevanssi' ), esc_html( $taxonomy_label ) );
					$dropdown     = '<label class="relevanssi-search-form__field"><span class="relevanssi-search-form__field-label">'
						. $filter_label
						. '</span>' . $dropdown . '</label>';
				}
				$additional_fields[] = $dropdown;
			} elseif ( 'checklist' === $key && 'post_type' !== $value ) {
				$name = $value;
				if ( 'category' === $value ) {
					$name = 'cat';
				}
				if ( 'post_tag' === $value ) {
					$name = 'tag';
				}
				$args = array(
					'taxonomy' => $value,
					'echo'     => 0,
				);
				if ( ! function_exists( 'wp_terms_checklist' ) ) {
					include ABSPATH . 'wp-admin/includes/template.php';
				}
				$checklist_items = wp_terms_checklist( 0, $args );
				$checklist_items = str_replace( 'post_category', 'cats', $checklist_items );
				$checklist_items = str_replace( 'tax_input[post_tag]', 'tags', $checklist_items );
				$checklist_items = str_replace( "disabled='disabled'", '', $checklist_items );
				$checklist_items = preg_replace( '/tax_input\[(.*?)\]/', '\1', $checklist_items );
				if ( $modal_context && ! empty( $checklist_items ) ) {
					$taxonomy_label  = $value;
					$taxonomy_object = get_taxonomy( $value );
					if ( $taxonomy_object && isset( $taxonomy_object->labels->name ) ) {
						$taxonomy_label = $taxonomy_object->labels->name;
					}
					$taxonomy_class = sanitize_html_class( $value );
					/* translators: %s: taxonomy name. */
					$filter_label    = sprintf( esc_html__( 'Filter by %s', 'relevanssi' ), esc_html( $taxonomy_label ) );
					$checklist_items = '<fieldset class="relevanssi-search-form__checklist relevanssi-search-form__checklist--' . esc_attr( $taxonomy_class ) . '"><legend>'
						. $filter_label
						. '</legend><ul class="categorychecklist form-no-clear">' . $checklist_items . '</ul></fieldset>';
				}
				$additional_fields[] = $checklist_items;
			} else {
				$key   = esc_attr( $key );
				$value = esc_attr( $value );

				$additional_fields[] = "<input type='hidden' name='$key' value='$value' />";
			}
		}
		$form = str_replace( '</form>', implode( "\n", $additional_fields ) . '</form>', $form );
	}
	/**
	 * Filters the Relevanssi shortcode search form before it's used.
	 *
	 * @param string $form The form HTML code.
	 * @param array  $atts The shortcode attributes.
	 */
	return apply_filters( 'relevanssi_search_form', $form, $atts );
}

/**
 * Returns a "did you mean?" block.
 *
 * This shortcode allows the Relevanssi "Did you mean?" functionality to be
 * placed anywhere in a post or page, which is essential for Block Themes
 * where the search template cannot be easily edited.
 *
 * Usage: [rlv_didyoumean n="5" pre="<strong>Did you mean: </strong>"]
 *
 * @param array $atts {
 *     Optional. Associative array of shortcode attributes.
 *
 *     @type string $query The search term to check. Defaults to the current search query.
 *     @type string $pre   Text or HTML to display before the suggestion.
 *     @type string $post  Text or HTML to display after the suggestion.
 *     @type int    $n     The maximum number of results to trigger the suggestion.
 * }
 *
 * @return string The "Did you mean?" HTML or an empty string if no suggestion.
 */
function relevanssi_didyoumean_shortcode( $atts ) {
	$didyoumean = '';
	$atts       = shortcode_atts(
		array(
			'query' => '',
			'pre'   => '<p>Did you mean: ',
			'post'  => '</p>',
			'n'     => 5,
		),
		$atts
	);

	$search_term = $atts['query'];
	if ( empty( $search_term ) ) {
		$search_term = get_search_query( false );
	}

	$didyoumean = relevanssi_didyoumean(
		$search_term,
		$atts['pre'],
		$atts['post'],
		(int) $atts['n'],
		false
	);

	return wp_kses_post( $didyoumean ?? '' );
}
